// 管径呼称 → 外径（配管種別ごとの読み替え） SGP/SUS/VP
export function pipeOD(nominal, kind = 'SGP') {
  const n = String(nominal).replace(/[^0-9A-Z./]/gi, '');
  if (kind === 'VP' || kind === 'VU') { const v = PVC[n.replace('A', '')]; return v ? v.od : null; }
  const p = PIPES[n.endsWith('A') ? n : n + 'A']; return p ? p.od : null;
}
