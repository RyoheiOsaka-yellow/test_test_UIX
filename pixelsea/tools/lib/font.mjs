// A 3x5 pixel font for labels on contact sheets (A-Z, 0-9 and a little punctuation).
const G = {
  A: "010101111101101", B: "110101110101110", C: "011100100100011", D: "110101101101110", E: "111100110100111", F: "111100110100100",
  G: "011100101101011", H: "101101111101101", I: "111010010010111", J: "001001001101010", K: "101101110101101", L: "100100100100111",
  M: "101111111101101", N: "110101101101101", O: "010101101101010", P: "110101110100100", Q: "010101101110011", R: "110101110101101",
  S: "011100010001110", T: "111010010010010", U: "101101101101111", V: "101101101101010", W: "101101111111101", X: "101101010101101",
  Y: "101101010010010", Z: "111001010100111", 0: "111101101101111", 1: "010110010010111", 2: "111001111100111", 3: "111001011001111",
  4: "101101111001001", 5: "111100111001111", 6: "111100111101111", 7: "111001010010010", 8: "111101111101111", 9: "111101111001111",
  "-": "000000111000000", ".": "000000000000010", "/": "001001010100100", " ": "000000000000000", ":": "000010000010000", "'": "010010000000000",
};
/** Draw str with fn(x, y) per lit pixel, its top-left at (x, y), scale k. Returns the width in pixels. */
export function drawText(str, x, y, fn, k = 1) {
  let cx = x;
  for (const ch of str.toUpperCase()) {
    const g = G[ch] ?? G["."];
    for (let i = 0; i < 15; i++) if (g[i] === "1") for (let yy = 0; yy < k; yy++) for (let xx = 0; xx < k; xx++) fn(cx + (i % 3) * k + xx, y + Math.floor(i / 3) * k + yy);
    cx += 4 * k;
  }
  return cx - x - k;
}
export const textWidth = (str, k = 1) => str.length * 4 * k - k;
